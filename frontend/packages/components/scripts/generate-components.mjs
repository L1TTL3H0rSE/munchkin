import fs from "node:fs";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

export function componentIndex(paths) {
  const names = new Set();
  const lines = [];
  for (const file of [...paths].sort((a, b) => a.localeCompare(b, "en"))) {
    const name = path.basename(file, ".vue");
    if (!/^[A-Z][A-Za-z0-9]+$/.test(name) || names.has(name.toLowerCase())) {
      throw new Error(`Invalid or colliding component name: ${name}`);
    }
    names.add(name.toLowerCase());
    lines.push(`export {default as ${name}} from "./${file}";`);
  }
  if (lines.length === 0) {
    throw new Error("Component input is empty");
  }
  return "// Generated by scripts/generate-components.mjs.\n" + lines.join("\n") + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const directory = fileURLToPath(new URL("../src/components/", import.meta.url));
  const files = fs.readdirSync(directory, {recursive: true}).map(String)
    .filter((file) => file.endsWith(".vue")).map((file) => file.replaceAll("\\", "/"));
  fs.writeFileSync(path.join(directory, "index.ts"), componentIndex(files));
}
